/**
 * Writer for the GENERATED src/audio/sfxManifest.ts.
 *
 * It MERGES: whatever styles the caller built are replaced and everything else
 * is carried over from the file already on disk. `SFX_FRAMES` is typed
 * `Record<SfxStyle, …>`, so `npm run sfx -- musical` must rebuild one bank
 * without dropping the others' <Sequence> lengths — and a second bank builder
 * (a recorded sample bank you add yourself) can share the same manifest.
 */
import {writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

import {SFX_STYLES} from '../../src/audio/sfxEvents.ts';
import {SFX_FRAMES as EXISTING} from '../../src/audio/sfxManifest.ts';

const HERE = dirname(fileURLToPath(import.meta.url));
export const MANIFEST_TS = join(HERE, '..', '..', 'src', 'audio', 'sfxManifest.ts');

const FPS = 30;

/** seconds -> the <Sequence> length that still covers the decay tail */
export const framesFor = (durSec) => Math.ceil(durSec * FPS) + 1;

/**
 * @param {Record<string, Record<string, number>>} built  style -> variant -> frames
 */
export const writeManifest = (built) => {
  const merged = {...EXISTING, ...built};
  const missing = SFX_STYLES.filter((id) => !merged[id]);
  if (missing.length) {
    throw new Error(
      `sfxManifest: no asset lengths for ${missing.join(', ')} — ` +
        `build those styles first (SFX_FRAMES is Record<SfxStyle, …>)`
    );
  }

  const body = SFX_STYLES.map((id) => {
    const rows = Object.entries(merged[id])
      .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
      .map(([k, v]) => `    '${k}': ${v},`)
      .join('\n');
    // quoted: "calm-pad" is not a valid bare identifier
    return `  '${id}': {\n${rows}\n  },`;
  }).join('\n');

  writeFileSync(
    MANIFEST_TS,
    `/**
 * GENERATED by scripts/make-sfx.mjs — do not edit by hand.
 *
 * Length in frames (@${FPS}fps) of every SFX asset, i.e. how long the Remotion
 * <Sequence> wrapping it must stay alive so the decay/reverb tail is never cut
 * off. ceil(seconds * fps) + 1 frame of slack.
 */
import type {SfxStyle} from './sfxEvents';

export const SFX_FRAMES: Record<SfxStyle, Record<string, number>> = {
${body}
};
`
  );
};
